import time
import requests

"""
同步下载图片
"""

def download_img(url: str):
    print(f'开始下载：{url}')
    # 发送网络请求，西崽图片
    response = requests.get(url)
    print('下载完成')
    # 保存图片
    file_name = url.rsplit('_')[-1]
    with open(file_name, 'wb') as f:
        f.write(response.content)


